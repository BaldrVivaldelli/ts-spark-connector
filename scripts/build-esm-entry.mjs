// Writes dist/index.mjs and dist/index.d.mts, the package's ES module entry.
//
// The entry re-exports the CommonJS build instead of compiling the library a
// second time. ES module and CommonJS consumers therefore share one module
// instance: one set of classes, so `instanceof` checks on the error types keep
// working when an application mixes both formats (no dual-package hazard).
// gRPC and Arrow stay lazily loaded, and the CommonJS code keeps resolving the
// vendored .proto files through __dirname. The export list is read from the
// built CommonJS module, so it cannot drift from the public API.
//
// Runs after `tsc` as part of `npm run build`.

import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const connector = createRequire(import.meta.url)(join(dist, "index.js"));

const names = Object.keys(connector)
    .filter(name => name !== "__esModule" && name !== "default")
    .sort();
assert.ok(names.length > 0, "dist/index.js exports nothing; run tsc before this script");
for (const name of names) {
    assert.match(name, /^[A-Za-z_$][\w$]*$/, `export "${name}" cannot be re-exported by name`);
}

/** Reserved words (Spark's `typeof`, for one) are valid export names but not bindings. */
function isBindingName(name) {
    if (name === "await") return false; // reserved in module code only
    try {
        new Function(`"use strict"; let ${name};`);
        return true;
    } catch {
        return false;
    }
}
const plain = names.filter(isBindingName);
const aliased = names.filter(name => !isBindingName(name)).map(name => [name, `__${name}`]);
for (const [, local] of aliased) assert.ok(!names.includes(local), `alias ${local} collides with an export`);

const header = [
    "// Generated by scripts/build-esm-entry.mjs. The ES module entry re-exports the",
    "// CommonJS build, so both formats share one module instance.",
].join("\n");

// Node, Bun and Deno all bind a default import of a CommonJS module to its
// module.exports object, the same object require() returns.
writeFileSync(join(dist, "index.mjs"), [
    header,
    'import connector from "./index.js";',
    "",
    "export const {",
    ...plain.map(name => `    ${name},`),
    "} = connector;",
    ...(aliased.length === 0 ? [] : [
        "",
        "const {",
        ...aliased.map(([name, local]) => `    ${name}: ${local},`),
        "} = connector;",
        "export {",
        ...aliased.map(([name, local]) => `    ${local} as ${name},`),
        "};",
    ]),
    "",
    "export default connector;",
    "",
].join("\n"));

writeFileSync(join(dist, "index.d.mts"), [
    header,
    'import * as connector from "./index.js";',
    "",
    'export * from "./index.js";',
    "export default connector;",
    "",
].join("\n"));

// Load what was just written: every CommonJS export must come back by name and
// be the very same value, and the default export must be module.exports.
const entry = await import(pathToFileURL(join(dist, "index.mjs")).href);
assert.equal(entry.default, connector, "default export is not the CommonJS module");
for (const name of names) {
    assert.ok(name in entry, `dist/index.mjs does not export ${name}`);
    assert.equal(entry[name], connector[name], `dist/index.mjs exports a different ${name}`);
}
assert.equal(Object.keys(entry).length, names.length + 1, "dist/index.mjs exports names the CommonJS build lacks");

process.stdout.write(`dist/index.mjs re-exports ${names.length} bindings from dist/index.js\n`);
